$ErrorActionPreference = "Stop"
$Root = Split-Path -Parent $MyInvocation.MyCommand.Path
$Backend = Join-Path $Root "backend"
$Frontend = Join-Path $Root "frontend"
function Require-Command([string]$Name, [string]$WingetId, [string]$Label) {
  if (Get-Command $Name -ErrorAction SilentlyContinue) { return }
  if (Get-Command winget -ErrorAction SilentlyContinue) { winget install --id $WingetId -e --accept-source-agreements --accept-package-agreements; return }
  throw "$Label is missing. Install it, reopen PowerShell, and run setup.bat again."
}
Write-Host "CareMatrix setup" -ForegroundColor Cyan
Require-Command "python" "Python.Python.3.12" "Python 3.12"
Require-Command "node" "OpenJS.NodeJS.LTS" "Node.js LTS"
$envFile = Join-Path $Backend ".env.local"
if (-not (Test-Path $envFile)) {
  $dbUrl = Read-Host "PostgreSQL DATABASE_URL (Neon or local; leave blank to configure later)"
  Set-Content -Path $envFile -Value @("# Generated by setup.ps1", "CAREMATRIX_DB_BACKEND=postgres", "DATABASE_URL=$dbUrl", "HOST=0.0.0.0", "PORT=8000", "ALLOWED_ORIGINS=http://localhost:5173") -Encoding UTF8
} else { Write-Host "Keeping existing backend/.env.local" }
$venvPython = Join-Path $Backend ".venv\Scripts\python.exe"
if (-not (Test-Path $venvPython)) { & python -m venv (Join-Path $Backend ".venv") }
& $venvPython -m pip install --upgrade pip
& $venvPython -m pip install -r (Join-Path $Backend "requirements.txt")
Push-Location $Frontend; try { npm install } finally { Pop-Location }
Push-Location $Backend; try { & $venvPython -c "import main; print('Database schema is ready.')" } finally { Pop-Location }
$seed = Read-Host "Load the five demo hospitals, inventory, and demo accounts? (Y/N)"
if ($seed -match '^(y|yes)$') {
  $psql = Get-Command psql -ErrorAction SilentlyContinue
  $urlLine = Get-Content $envFile | Where-Object { $_ -like 'DATABASE_URL=*' } | Select-Object -First 1
  if ($psql -and $urlLine -and $urlLine.Length -gt 13) { & psql $urlLine.Substring(13) -v ON_ERROR_STOP=1 -f (Join-Path $Backend "seed_neon.sql") }
  else { Write-Warning "psql or DATABASE_URL is unavailable; demo seed was skipped." }
}
Write-Host "Setup complete." -ForegroundColor Green
Write-Host "Backend:  cd backend; .venv\Scripts\python.exe -m uvicorn main:app --reload --port 8000"
Write-Host "Frontend: cd frontend; npm run dev"
