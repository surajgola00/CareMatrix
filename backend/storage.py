"""Small database compatibility layer for the active CareMatrix API."""
import os
import re
import sqlite3
from urllib.parse import quote
from dotenv import dotenv_values

try:
    import psycopg
    from psycopg.rows import tuple_row
except ImportError:  # local SQLite remains available without the optional driver
    psycopg = None
    tuple_row = None


class HybridRow(tuple):
    def __new__(cls, values, columns):
        obj = super().__new__(cls, values)
        obj.columns = columns
        return obj

    def __getitem__(self, key):
        if isinstance(key, str):
            return super().__getitem__(self.columns.index(key))
        return super().__getitem__(key)

    def keys(self):
        return self.columns

    def __iter__(self):
        return super().__iter__()


def hybrid_row(cursor):
    if cursor.description is None:
        return lambda values: values
    columns = [item.name for item in cursor.description]
    return lambda values: HybridRow(values, columns)


def postgres_url():
    values = dotenv_values(".env.local")
    url = os.getenv("DATABASE_URL") or values.get("DATABASE_URL")
    if url:
        return url
    host = values.get("Host")
    if host and values.get("Database") and values.get("Username") and values.get("Password"):
        return "postgresql://{}:{}@{}:{}/{}".format(quote(values["Username"]), quote(values["Password"], safe=""), host, values.get("Port", "5432"), values["Database"])
    return None


USE_POSTGRES = bool(postgres_url()) and os.getenv("CAREMATRIX_DB_BACKEND", "postgres").lower() != "sqlite"


def _sql(query):
    ignored = bool(re.search(r"INSERT\s+OR\s+IGNORE", query, flags=re.I))
    query = re.sub(r"INSERT\s+OR\s+IGNORE", "INSERT", query, flags=re.I)
    if ignored and "ON CONFLICT" not in query.upper():
        query += " ON CONFLICT DO NOTHING"
    return query.replace("?", "%s")


class CompatConnection:
    def __init__(self, raw):
        self.raw = raw

    def execute(self, query, params=()):
        cur = CompatCursor(self.raw.cursor())
        cur.execute(query, params)
        return cur

    def cursor(self):
        return CompatCursor(self.raw.cursor())

    def commit(self):
        self.raw.commit()

    def rollback(self):
        self.raw.rollback()

    def close(self):
        self.raw.close()

    def executescript(self, script):
        for statement in script.split(";"):
            statement = statement.strip()
            if statement:
                self.execute(statement)


class CompatCursor:
    def __init__(self, raw):
        self.raw = raw

    def execute(self, query, params=()):
        self.raw.execute(_sql(query), params)
        return self

    def executemany(self, query, params):
        self.raw.executemany(_sql(query), params)
        return self

    def fetchone(self):
        return self.raw.fetchone()

    def fetchall(self):
        return self.raw.fetchall()

    def __iter__(self):
        return iter(self.raw)


def connect():
    if USE_POSTGRES:
        return CompatConnection(psycopg.connect(postgres_url(), row_factory=hybrid_row))
    path = os.getenv("CAREMATRIX_DB_PATH", "carematrix.db")
    conn = sqlite3.connect(path)
    conn.row_factory = sqlite3.Row
    return CompatConnection(conn)


def init_schema():
    conn = connect()
    conn.executescript("""
    CREATE TABLE IF NOT EXISTS hospitals (id TEXT PRIMARY KEY, name TEXT, lat REAL, lng REAL, status TEXT, location TEXT, logo_url TEXT, created_at INTEGER);
    CREATE TABLE IF NOT EXISTS capacity (hospital_id TEXT, department TEXT, total INTEGER, available INTEGER, PRIMARY KEY (hospital_id, department));
    CREATE TABLE IF NOT EXISTS patients (id TEXT PRIMARY KEY, department TEXT, priority TEXT, lat REAL, lng REAL, assigned INTEGER DEFAULT 0, status TEXT DEFAULT 'open', requester_hospital_id TEXT, created_at INTEGER, updated_at INTEGER);
    CREATE TABLE IF NOT EXISTS responses (id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, patient_id TEXT, hospital_id TEXT, status TEXT, timestamp INTEGER);
    CREATE TABLE IF NOT EXISTS assignments (patient_id TEXT, hospital_id TEXT, timestamp INTEGER);
    CREATE TABLE IF NOT EXISTS resource_requests (id TEXT PRIMARY KEY, requester_hospital_id TEXT, resource_type TEXT, quantity INTEGER, status TEXT DEFAULT 'open', timestamp INTEGER, selected_provider_id TEXT, created_at INTEGER, updated_at INTEGER);
    CREATE TABLE IF NOT EXISTS resource_responses (id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, request_id TEXT, provider_hospital_id TEXT, status TEXT, timestamp INTEGER);
    CREATE TABLE IF NOT EXISTS resources (hospital_id TEXT, resource_type TEXT, available INTEGER, PRIMARY KEY (hospital_id, resource_type));
    """)
    conn.commit(); conn.close()
